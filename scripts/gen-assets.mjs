// Generates src/data/Assets.ts: the list of texture atlases and the names of their frames,
// so that a typo in a frame name is a compile error.
//
//   node scripts/gen-assets.mjs           write the file
//   node scripts/gen-assets.mjs --check   fail if the file is out of date (CI)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const root = fileURLToPath(new URL('..', import.meta.url));
const atlasDir = join(root, 'public/assets/atlases');
const outFile = join(root, 'src/data/Assets.ts');

/** Frame names of an atlas in any of the formats Phaser reads. */
function frameNames(data, file) {
  // TexturePacker "Phaser 3" format: { textures: [{ image, frames: [{ filename }] }] }
  if (Array.isArray(data.textures)) {
    if (data.textures.length !== 1) {
      throw new Error(`${file}: multi-page atlases are not supported, pack it into one image.`);
    }
    return data.textures[0].frames.map((frame) => frame.filename);
  }
  // JSON Array: { frames: [{ filename }] }
  if (Array.isArray(data.frames)) return data.frames.map((frame) => frame.filename);
  // JSON Hash: { frames: { name: {...} } }
  if (data.frames && typeof data.frames === 'object') return Object.keys(data.frames);
  throw new Error(`${file}: unknown atlas format, no frames found.`);
}

function readAtlases() {
  const files = readdirSync(atlasDir)
    .filter((file) => file.endsWith('.json'))
    .sort();
  return files.map((file) => {
    const key = basename(file, '.json');
    if (!existsSync(join(atlasDir, `${key}.png`))) {
      throw new Error(`${file}: the image ${key}.png is missing next to it.`);
    }
    const frames = frameNames(JSON.parse(readFileSync(join(atlasDir, file), 'utf8')), file);
    return { key, frames: [...new Set(frames)].sort() };
  });
}

function render(atlases) {
  const quote = (value) => JSON.stringify(value);
  const lines = [
    '// Generated by `npm run gen:assets` from public/assets/atlases. Do not edit.',
    '',
    '/** Texture atlases: `<key>.png` and `<key>.json`. All of them are loaded in PreloaderScene. */',
    `export const ATLASES = [${atlases.map((atlas) => quote(atlas.key)).join(', ')}] as const;`,
    '',
    'export type AtlasKey = (typeof ATLASES)[number];',
    '',
    '/** Frame names of every atlas. */',
    'export type AtlasFrames = {',
    ...atlases.map(
      (atlas) => `  ${quote(atlas.key)}: ${atlas.frames.map(quote).join(' | ') || 'never'};`
    ),
    '};',
    '',
    '/** A frame of any atlas. */',
    'export type AtlasFrame = AtlasFrames[AtlasKey];',
    '',
  ];
  return lines.join('\n');
}

const source = render(readAtlases());
const options = await prettier.resolveConfig(outFile);
const formatted = await prettier.format(source, { ...options, filepath: outFile });
const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
const name = relative(root, outFile);

if (process.argv.includes('--check')) {
  if (current !== formatted) {
    console.error(`✗ ${name} is out of date. Run: npm run gen:assets`);
    process.exit(1);
  }
  console.log(`✓ ${name} is up to date`);
} else if (current === formatted) {
  console.log(`✓ ${name} is up to date`);
} else {
  writeFileSync(outFile, formatted);
  console.log(`✓ ${name} written`);
}
